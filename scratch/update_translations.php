$baseDir = dirname(__DIR__);
$directories = [
    $baseDir . '/packages/automas/LandingPage/src/Resources/lang',
    $baseDir . '/resources/lang'
];

foreach ($directories as $dir) {
    if (!is_dir($dir)) continue;

    foreach ($languages as $lang) {
        $filePath = $dir . DIRECTORY_SEPARATOR . $lang . '.json';
        if (!file_exists($filePath)) continue;

        $content = json_decode(file_get_contents($filePath), true) ?: [];
        $sourceTranslations = $translationsByLang[$lang] ?? $translationsByLang['en'];

        foreach ($sourceTranslations as $key => $val) {
            if (!isset($content[$key]) || $content[$key] === $key) {
                $content[$key] = $val;
            }
        }

        // Sort keys alphabetically for clean consistency
        ksort($content);

        file_put_contents($filePath, json_encode($content, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES));
        echo "Updated {$filePath}\n";
    }
}

